/** Parse `'09090:99999:…'` into pixels plus its dimensions. */
export function parseImage(spec: string): { width: number; height: number; pixels: number[] } {
  const rows = spec.replace(/\s+/g, '').split(':').filter((r) => r.length > 0);
  const width = Math.max(...rows.map((r) => r.length), 1);
  const pixels: number[] = [];
  for (const row of rows) {
    for (let x = 0; x < width; x++) {
      const ch = row[x];
      pixels.push(ch === undefined ? 0 : Math.max(0, Math.min(9, Number(ch) || 0)));
    }
  }
  return { width, height: rows.length, pixels };
}

export function imageToSpec(width: number, height: number, pixels: number[]): string {
  const rows: string[] = [];
  for (let y = 0; y < height; y++) {
    rows.push(pixels.slice(y * width, (y + 1) * width).map((p) => String(p)).join(''));
  }
  return rows.join(':');
}
