const UNKNOWN = '#####' + '#...#' + '#...#' + '#...#' + '#####';

/** A character's 5 × 5 bitmap as 25 brightness values, 0 or 9. */
export function glyph(ch: string): number[] {
  const rows = G[ch] ?? UNKNOWN;
  return [...rows].map((c) => (c === '#' ? 9 : 0));
}

